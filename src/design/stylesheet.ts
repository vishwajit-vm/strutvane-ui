/**
 * The stylesheet a design becomes: its tokens as CSS custom properties, scoped to the
 * `<DesignProvider>` root, followed by the design's own CSS.
 *
 * ```css
 * :where(:root) { --brand-hue: 264; --font-sans: …; --radius: 6px; --density: 1 }   (defaults)
 * [data-sv-design="crisp"], [data-sv-design="crisp"] [data-sv-density] { --sv-radius-md: …; … }
 * [data-sv-design="crisp"] [data-sv-density="compact"] { --sv-density-step: 0.8 }
 * [data-sv-design="crisp"][data-sv-theme="light"] { color-scheme: light; --sv-bg: …; … }
 * [data-sv-design="crisp"][data-sv-theme="dark"] { color-scheme: dark; … }
 * (font faces) (the design's stylesheet) (overrides from <DesignProvider overrides>)
 * ```
 *
 * Why this shape:
 * - The public tokens' defaults sit on `:where(:root)` (zero specificity), so an app's own
 *   `:root { --brand-hue: 150 }` in `resources/ui/theme.css` wins without `!important`.
 * - Size tokens are declared again on every `[data-sv-density]` element, because a custom
 *   property's `var()` is resolved where it is declared: a list switched to compact rows must
 *   recompute its heights itself.
 * - Every value was checked by `defineDesign` (no `;`, `{`, `}`, `<`), and the design name is a
 *   plain id, so nothing here can break out of a declaration or the `<style>` element.
 *
 * @module
 */
import { resolveVars } from './color.ts'
import { type Design, safeOverrides } from './define-design.ts'
import {
  COLOR_TOKENS,
  chartVar,
  cssVar,
  EXTRA_VARS,
  type PublicOverrides,
  SCALE_TOKENS,
} from './tokens.ts'

/** Light or dark. */
export type ThemeName = 'light' | 'dark'

/** How much a compact list shrinks its controls and rows. */
export const COMPACT_STEP = 0.8

/** The size tokens that follow the row-density toggle. */
const DENSITY_TOKENS: ReadonlySet<string> = new Set(['controlHeight', 'rowHeight'])

const decl = (name: string, value: string | number): string => `${name}:${value};`

/** The public token declarations for a set of values. */
function publicDeclarations(values: {
  brandHue?: number | undefined
  fontSans?: string | undefined
  radius?: string | undefined
  density?: number | undefined
}): string {
  return [
    values.brandHue === undefined ? '' : decl('--brand-hue', values.brandHue),
    values.fontSans === undefined ? '' : decl('--font-sans', values.fontSans),
    values.radius === undefined ? '' : decl('--radius', values.radius),
    values.density === undefined ? '' : decl('--density', values.density),
  ].join('')
}

/** The size, font declarations of a design (one string). */
function scaleDeclarations(design: Design): string {
  const sizes = SCALE_TOKENS.map((token) => {
    const value = design.scale[token]
    return decl(
      cssVar(token),
      DENSITY_TOKENS.has(token) ? `calc((${value}) * var(--sv-density-step, 1))` : value,
    )
  })
  return [
    decl(EXTRA_VARS.fontSans, 'var(--font-sans)'),
    decl(EXTRA_VARS.fontMono, design.fonts.mono),
    ...sizes,
  ].join('')
}

/** The colour, chart and shadow declarations of one theme. */
function themeDeclarations(design: Design, theme: ThemeName): string {
  const tokens = design.tokens[theme]
  return [
    decl('color-scheme', theme),
    ...COLOR_TOKENS.map((token) => decl(cssVar(token), tokens.color[token])),
    ...design.chartPalette[theme].map((color, i) => decl(chartVar(i + 1), color)),
    decl(EXTRA_VARS.shadowSm, tokens.shadow.sm),
    decl(EXTRA_VARS.shadowPop, tokens.shadow.pop),
  ].join('')
}

/** The selector of the provider root for a design. */
export function designSelector(design: Design): string {
  return `[data-sv-design="${design.name}"]`
}

/** Options for {@link designStylesheet}. */
export interface StylesheetOptions {
  /** Public override values for this app (invalid values are dropped). */
  readonly overrides?: PublicOverrides
}

/**
 * The full CSS of a design. `<DesignProvider>` injects it in a `<style nonce>`; an app with a
 * strict CSP and no nonce can serve it as a file instead (`injectStyles={false}`).
 *
 * @example
 * writeFileSync('public/design.css', designStylesheet(crisp, { overrides: { brandHue: 150 } }))
 */
export function designStylesheet(design: Design, options: StylesheetOptions = {}): string {
  const root = designSelector(design)
  const overrides = safeOverrides(options.overrides ?? {})
  const defaults = design.defaults
  const blocks = [
    `/* ${design.name} design, generated by @strutvane/ui. Do not edit: change the design. */`,
    `:where(:root){${publicDeclarations({ ...defaults, fontSans: design.fonts.sans })}}`,
    `${root},${root} [data-sv-density]{${scaleDeclarations(design)}}`,
    `${root} [data-sv-density="compact"]{${decl('--sv-density-step', COMPACT_STEP)}}`,
    `${root}[data-sv-theme="light"]{${themeDeclarations(design, 'light')}}`,
    `${root}[data-sv-theme="dark"]{${themeDeclarations(design, 'dark')}}`,
    design.fonts.faces ?? '',
    design.stylesheet,
  ]
  const own = publicDeclarations(overrides)
  if (own !== '') blocks.push(`${root}{${own}}`)
  return `${blocks.filter((b) => b !== '').join('\n')}\n`
}

/**
 * The custom properties in effect at the provider root, fully resolved, for one theme and set of
 * overrides: what a browser computes there. Used by the conformance kit to check contrast and
 * that every public override changes the result. Unresolvable values are left out.
 *
 * @example
 * resolveDesignTokens(plain, 'dark', { brandHue: 150 }).get('--sv-accent')
 */
export function resolveDesignTokens(
  design: Design,
  theme: ThemeName,
  overrides: PublicOverrides = {},
  density: 'default' | 'compact' = 'default',
): Map<string, string> {
  return resolveDeclarations(declaredAt(design, theme, overrides, density))
}

/** The raw declarations in effect at the provider root (later wins), before `var()` resolution. */
export function declaredAt(
  design: Design,
  theme: ThemeName,
  overrides: PublicOverrides = {},
  density: 'default' | 'compact' = 'default',
): Map<string, string> {
  const css = designStylesheet(design, { overrides })
  const root = designSelector(design)
  const applies = new Set([
    ':where(:root)',
    root,
    `${root} [data-sv-density]`,
    `${root}[data-sv-theme="${theme}"]`,
    ...(density === 'compact' ? [`${root} [data-sv-density="compact"]`] : []),
  ])
  return customPropertiesFor(css, (selector) => applies.has(selector))
}

/**
 * Collect the custom properties declared in `css` by rules whose selector list contains a
 * selector `matches` accepts. Later declarations win, as in the cascade for equal specificity.
 * Only plain top-level rules are read; at-rules are skipped.
 */
export function customPropertiesFor(
  css: string,
  matches: (selector: string) => boolean,
): Map<string, string> {
  const out = new Map<string, string>()
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, '')
  for (const rule of withoutComments.matchAll(/([^{}@]+)\{([^{}]*)\}/g)) {
    const selectors = (rule[1] ?? '').split(',').map((s) => s.trim())
    if (!selectors.some(matches)) continue
    for (const d of (rule[2] ?? '').matchAll(/(--[\w-]+)\s*:\s*([^;]+);?/g))
      if (d[1] !== undefined && d[2] !== undefined) out.set(d[1], d[2].trim())
  }
  return out
}

/** Resolve every `var()` in a declaration map; unresolvable entries are dropped. */
export function resolveDeclarations(declared: ReadonlyMap<string, string>): Map<string, string> {
  const out = new Map<string, string>()
  for (const [name, value] of declared) {
    const resolved = resolveVars(value, declared, new Set([name]))
    if (resolved !== undefined) out.set(name, resolved)
  }
  return out
}
